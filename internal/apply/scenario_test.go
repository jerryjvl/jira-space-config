// Scenarios start from the recorded TS space and its own export, edit the
// spec, and add answers for the lookups the edit makes the dry run do.

const tsWorkflow = "Software Simplified Workflow for Project TS"

// scenario is one edit of the TS spec.
type scenario struct {
	name   string
	edit   []string          // pairs: text to replace, replacement
	files  map[string]string // extra fixture files
	routes []jiratest.Route  // extra routes
	// replace, when set, changes a recorded file: name → edit of its text.
	replace map[string][2]string
	// section, when set, replaces the spec's text from section[0] up to
	// (not including) section[1] with section[2].
	section [3]string
	// allowUpdate are the --allow-update kinds the dry run is given.
	allowUpdate []string
	want        []string
}

func (sc scenario) run(t *testing.T) string {
	t.Helper()
	dir := t.TempDir()
	entries, err := os.ReadDir("testdata/ts")
	if err != nil {
		t.Fatal(err)
	}
	for _, e := range entries {
		data, err := os.ReadFile(filepath.Join("testdata/ts", e.Name()))
		if err != nil {
			t.Fatal(err)
		}
		if r, ok := sc.replace[e.Name()]; ok {
			if !bytes.Contains(data, []byte(r[0])) {
				t.Fatalf("%s does not contain %q", e.Name(), r[0])
			}
			data = bytes.ReplaceAll(data, []byte(r[0]), []byte(r[1]))
		}
		writeFile(t, filepath.Join(dir, e.Name()), string(data))
	}
	for name, text := range sc.files {
		writeFile(t, filepath.Join(dir, name), text)
	}
	routes, err := jiratest.LoadRoutes(dir)
	if err != nil {
		t.Fatal(err)
	}
	for _, r := range sc.routes {
		replaced := false
		for i := range routes {
			if methodOf(routes[i]) == methodOf(r) && routes[i].Path == r.Path && routes[i].Query.Encode() == r.Query.Encode() && routes[i].Body == r.Body {
				routes[i], replaced = r, true
			}
		}
		if !replaced {
			routes = append(routes, r)
		}
	}
	text, err := os.ReadFile(filepath.Join(dir, "spec.yaml"))
	if err != nil {
		t.Fatal(err)
	}
	s := string(text)
	for i := 0; i+1 < len(sc.edit); i += 2 {
		if !strings.Contains(s, sc.edit[i]) {
			t.Fatalf("spec does not contain %q", sc.edit[i])
		}
		s = strings.Replace(s, sc.edit[i], sc.edit[i+1], 1)
	}
	if sc.section[0] != "" {
		start := strings.Index(s, sc.section[0])
		end := strings.Index(s[start:], sc.section[1])
		if start < 0 || end < 0 {
			t.Fatalf("spec has no section from %q to %q", sc.section[0], sc.section[1])
		}
		s = s[:start] + sc.section[2] + s[start+end:]
	}
	srv := jiratest.New(t, dir, routes)
	var out bytes.Buffer
	_ = DryRun(context.Background(), srv.Client(), Options{SpecFile: "spec.yaml", Spec: []byte(s), SpaceKey: "TS", AllowUpdate: sc.allowUpdate}, &out)
	return out.String()
}

func writeFile(t *testing.T, path, text string) {
	t.Helper()
	if err := os.WriteFile(path, []byte(text), 0o600); err != nil { //nolint:gosec // G703: the test's own temp directory
		t.Fatal(err)
	}
}

func page(values string) string {
	return `{"isLast":true,"startAt":0,"maxResults":50,"values":` + values + `}`
}

// Edits shared by the scenarios.
var (
	prefix      = []string{"space:\n  key: TS\n", "space:\n  key: TS\n  managed_prefix: TS\n"}
	bugWorkflow = []string{"    - name: Bug\n      workflow: " + tsWorkflow, "    - name: Bug\n      workflow: TS Triage Workflow"}
	noWFBinding = []string{"    workflow_scheme:\n      name: 'TS: Software Simplified Workflow Scheme'\n      id: \"10003\"\n      mode: reuse\n" +
		"      description: Generated by JIRA Software version 1001.0.0-SNAPSHOT. This workflow scheme is managed internally by Jira. Do not manually modify this workflow scheme.\n", ""}
	workflowScheme = func(name, description, bug string) string {
		return `{"id": 10200, "name": "` + name + `", "description": "` + description + `", "defaultWorkflow": "` + tsWorkflow +
			`", "issueTypeMappings": {"10013": "` + bug + `"}}`
	}
	schemesRoute = jiratest.Route{Path: "/rest/api/3/workflowscheme", File: "workflowschemes.json"}
	marker       = "[managed-by: jira-space-config]"
)

func edits(parts ...[]string) []string {
	var out []string
	for _, p := range parts {
		out = append(out, p...)
	}
	return out
}

func TestSchemeScenarios(t *testing.T) {
	wf := edits(prefix, bugWorkflow, noWFBinding)
	tests := []scenario{
		{name: "a new workflow scheme", edit: wf,
			files:  map[string]string{"workflowschemes.json": page(`[]`)},
			routes: []jiratest.Route{schemesRoute},
			want:   []string{"+ create   Workflow scheme", `new workflow scheme "TS Workflow Scheme"`, "step 25 switches the space to it"}},
		{name: "a matching managed scheme to switch to", edit: wf,
			files:  map[string]string{"workflowschemes.json": page(`[` + workflowScheme("TS Workflow Scheme", "x "+marker, "TS Triage Workflow") + `]`)},
			routes: []jiratest.Route{schemesRoute},
			want:   []string{"~ update   Workflow scheme", `"TS Workflow Scheme" (id 10200) matches`}},
		{name: "a scheme of that name the tool did not make", edit: wf,
			files:  map[string]string{"workflowschemes.json": page(`[` + workflowScheme("TS Workflow Scheme", "made by hand", "TS Triage Workflow") + `]`)},
			routes: []jiratest.Route{schemesRoute},
			want:   []string{"✗ error    Workflow scheme", `"TS Workflow Scheme" (id 10200) exists, but this tool did`}},
		{name: "a managed scheme that differs", edit: wf,
			files:  map[string]string{"workflowschemes.json": page(`[` + workflowScheme("TS Workflow Scheme", marker, tsWorkflow) + `]`)},
			routes: []jiratest.Route{schemesRoute},
			want:   []string{`"TS Workflow Scheme" (id 10200) exists but does not match the`, "spec: TS Triage Workflow"}},
		{name: "two schemes of that name", edit: wf,
			files: map[string]string{"workflowschemes.json": page(`[` + workflowScheme("TS Workflow Scheme", marker, tsWorkflow) + "," +
				workflowScheme("TS Workflow Scheme", marker, tsWorkflow) + `]`)},
			routes: []jiratest.Route{schemesRoute},
			want:   []string{`2 workflow schemes on the site are named "TS Workflow Scheme"`}},
		{name: "no prefix to name a new scheme", edit: edits(bugWorkflow, noWFBinding),
			want: []string{"a new workflow scheme needs a name", "Set space.managed_prefix"}},
		{name: "a reused scheme that does not exist",
			edit:   edits(bugWorkflow, []string{"      name: 'TS: Software Simplified Workflow Scheme'\n", "      name: Missing Scheme\n"}),
			files:  map[string]string{"workflowschemes.json": page(`[]`)},
			routes: []jiratest.Route{schemesRoute},
			want:   []string{`the spec's binding names "Missing Scheme", which does not exist`}},
		{name: "the space's own managed scheme differs", edit: bugWorkflow,
			replace: map[string][2]string{"get_workflowscheme_project_d5d94ce9.json": {"Do not manually modify this workflow scheme.", "Do not manually modify this workflow scheme. " + marker}},
			files:   map[string]string{"wfs_usages.json": `{"workflowSchemeId":"10003","projects":{"values":[{"id":"10002"}]}}`},
			routes:  []jiratest.Route{{Path: "/rest/api/3/workflowscheme/10003/projectUsages", File: "wfs_usages.json"}},
			want:    []string{"~ update   Workflow scheme", "used by this space alone, is changed to match (altering):"}},
		{name: "the space's own managed scheme differs, and another space uses it", edit: bugWorkflow,
			replace: map[string][2]string{"get_workflowscheme_project_d5d94ce9.json": {"Do not manually modify this workflow scheme.", "Do not manually modify this workflow scheme. " + marker}},
			files:   map[string]string{"wfs_usages.json": `{"workflowSchemeId":"10003","projects":{"values":[{"id":"10002"},{"id":"10009"}]}}`},
			routes:  []jiratest.Route{{Path: "/rest/api/3/workflowscheme/10003/projectUsages", File: "wfs_usages.json"}},
			want:    []string{"✗ error    Workflow scheme", "another space uses it too", "10009", "is never changed"}},
		{name: "a new issue type scheme",
			edit: edits(prefix, []string{"    - name: Task\n      workflow: " + tsWorkflow + "\n      screens: 'TS: Kanban Default Issue Screen'\n      binding:\n        screen_scheme: {name: 'TS: Kanban Default Screen Scheme', id: \"10012\", mode: reuse}\n", "",
				"    issue_type_scheme: {name: 'TS: Kanban Issue Type Scheme', id: \"10146\", mode: reuse}\n", ""}),
			files: map[string]string{"its.json": page(`[{"id":"10300","name":"TS Issue Type Scheme","description":"by hand","defaultIssueTypeId":"10000"}]`),
				"its_mapping.json": page(`[{"issueTypeId":"10012"},{"issueTypeId":"10000"}]`)},
			routes: []jiratest.Route{{Path: "/rest/api/3/issuetypescheme", File: "its.json"}, {Path: "/rest/api/3/issuetypescheme/mapping", File: "its_mapping.json"}},
			want:   []string{"✗ error    Issue type scheme", `"TS Issue Type Scheme" (id 10300) exists, but this tool did`}},
		{name: "a matching managed screen scheme to switch to",
			edit: edits(prefix, []string{"      screens: 'TS: Kanban Bug Screen'\n", "      screens: 'TS: Kanban Default Issue Screen'\n",
				"    issue_type_screen_scheme: {name: 'TS: Kanban Issue Type Screen Scheme', id: \"10002\", mode: reuse}\n", ""}),
			files: map[string]string{"itss.json": page(`[{"id":"10400","name":"TS Issue Type Screen Scheme","description":"` + marker + `"}]`),
				"itss_mapping.json": page(`[{"issueTypeId":"default","screenSchemeId":"10012"},{"issueTypeId":"10000","screenSchemeId":"10014"}]`),
				"ss.json":           page(`[{"id":10012,"name":"a","screens":{"default":10012}},{"id":10014,"name":"b","screens":{"default":10014}}]`),
				"screens.json":      page(`[{"id":10012,"name":"TS: Kanban Default Issue Screen"},{"id":10014,"name":"TS: Kanban Epic Screen"}]`)},
			routes: []jiratest.Route{{Path: "/rest/api/3/issuetypescreenscheme", File: "itss.json"}, {Path: "/rest/api/3/issuetypescreenscheme/mapping", File: "itss_mapping.json"},
				{Path: "/rest/api/3/screenscheme", Query: url.Values{"id": {"10012", "10014"}}, File: "ss.json"},
				{Path: "/rest/api/3/screens", Query: url.Values{"id": {"10012", "10014"}}, File: "screens.json"}},
			want: []string{"~ update   Issue type screen scheme", `"TS Issue Type Screen Scheme" (id 10400)`}},
		{name: "a new field scheme",
			edit: edits(prefix, []string{"    field_scheme: {name: Default Field Scheme, id: \"1\", mode: reuse, site_default: true}\n", "",
				"    - name: Summary\n      required: true\n", "    - name: Summary\n      required: true\n      description: What was found\n"}),
			files:  map[string]string{"fieldschemes.json": page(`[]`)},
			routes: []jiratest.Route{{Path: "/rest/api/3/config/fieldschemes", File: "fieldschemes.json"}},
			want:   []string{`+ create   Field scheme  new field scheme "TS Field Scheme"`}},
		{name: "a spec for the other field backend",
			edit: []string{"field_backend: field_schemes", "field_backend: field_configurations"},
			want: []string{"✗ error    Field backend", "the spec was written for a site with field configurations; this site", "uses field schemes"}},
		{name: "a context for a field the site does not have",
			edit: []string{"    Change reason:\n", "    Change reasons:\n"},
			want: []string{"✗ error    Change reasons  no custom field on the site has this name"}},
		{name: "a shared context that differs",
			edit: []string{"options: [Repair, Upgrade, Maintenance, New functionality, Other]", "options: [Repair, Upgrade]"},
			want: []string{"✗ differs  Change reason", "context is used by other spaces too, and is never changed."}},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			got := tc.run(t)
			for _, w := range tc.want {
				if !strings.Contains(got, w) {
					t.Errorf("output lacks %q:\n%s", w, got)
				}
			}
		})
	}
}

// TestNewSchemesNeedAdministerJira: without Administer Jira, a scheme
// that would be created is an error.
func TestNewSchemesNeedAdministerJira(t *testing.T) {
	sc := scenario{edit: edits(prefix, bugWorkflow, noWFBinding),
		files:   map[string]string{"workflowschemes.json": page(`[]`)},
		routes:  []jiratest.Route{schemesRoute},
		replace: map[string][2]string{"get_mypermissions_14e19acb.json": {"editing system email settings.\",\n      \"havePermission\": true", "editing system email settings.\",\n      \"havePermission\": false"}},
	}
	if got := sc.run(t); !strings.Contains(got, `a new workflow scheme "TS Workflow Scheme" is needed, and this account`) {
		t.Errorf("output:\n%s", got)
	}
}

// Edits for the space's own configuration.
var (
	morePermissions = []string{"      ADD_COMMENTS: [application_role, 'role:atlassian-addons-project-access']\n",
		"      ADD_COMMENTS: [application_role, 'role:Administrators', 'role:atlassian-addons-project-access']\n"}
	noPermissionBinding = []string{"    binding:\n      name: Default software scheme\n      id: \"10002\"\n      mode: reuse\n" +
		"      description: Default scheme for Software projects.\n", ""}
	permissionSchemes = jiratest.Route{Path: "/rest/api/3/permissionscheme", File: "permissionschemes.json"}
	noSchemes         = map[string]string{"permissionschemes.json": `{"permissionSchemes":[]}`}
)

func TestSpaceScenarios(t *testing.T) {
	tests := []scenario{
		{name: "a new permission scheme granting to every user",
			edit: edits(prefix, morePermissions, noPermissionBinding), files: noSchemes, routes: []jiratest.Route{permissionSchemes},
			want: []string{"✗ error    Permission scheme", "ADD_COMMENTS, ASSIGNABLE_USER, ASSIGN_ISSUES and", "to every user", "Granting to every"}},
		{name: "a new permission scheme granting to every user, allowed",
			edit: edits(prefix, morePermissions, noPermissionBinding), files: noSchemes, routes: []jiratest.Route{permissionSchemes},
			allowUpdate: []string{"permissions"},
			want:        []string{"+ create   Permission scheme", "Overrides  --allow-update=permissions"}},
		{name: "a new permission scheme on the Free plan",
			edit: edits(prefix, morePermissions, noPermissionBinding), files: noSchemes, routes: []jiratest.Route{permissionSchemes},
			replace: map[string][2]string{"get_instance_license.json": {`"plan": "PAID"`, `"plan": "FREE"`}},
			want:    []string{"this site is on", "the Free plan", "On the Free plan Jira's permissions are fixed"}},
		{name: "a priority scheme that drops a priority work items have",
			edit: edits(prefix, []string{"    priorities: [Highest, High, Medium, Low, Lowest]\n    default: Medium\n    binding:\n" +
				"      name: Default priority scheme\n      id: \"10124\"\n      mode: reuse\n      site_default: true\n" +
				"      description: This is the default scheme used by all new and unassigned projects\n",
				"    priorities: [Highest, High, Medium, Low]\n    default: Medium\n"}),
			replace: map[string][2]string{"post_search_approximate-count_2f78ef3f.json": {`"count": 0`, `"count": 5`}},
			files:   map[string]string{"priorityschemes.json": page(`[]`), "count_lowest.json": `{"count": 3}`},
			routes: []jiratest.Route{{Path: "/rest/api/3/priorityscheme", Query: url.Values{"schemeName": {"TS Priority Scheme"}}, File: "priorityschemes.json"},
				{Method: http.MethodPost, Path: "/rest/api/3/search/approximate-count", Body: `{"jql":"project = 10002 AND priority = \"Lowest\""}`, File: "count_lowest.json"}},
			want: []string{`■ blocked  priority "Lowest"`, "3 work items have this priority, which the new scheme lacks", "Change their priority first"}},
		{name: "another type of space",
			edit: []string{"    type: software\n", "    type: business\n"},
			want: []string{"✗ error    Details", "the spec gives another type of space", "Jira cannot change a space's type"}},
		{name: "components: an unknown ID, a new one, and one only Jira has",
			edit:    []string{"  role_members:\n", "  components:\n    - {name: API, id: \"99999\"}\n    - {name: Web}\n\n  role_members:\n"},
			replace: map[string][2]string{"get_project_TS_component_bd9b64c8.json": {`"values": []`, `"values": [{"id": "10500", "name": "Legacy", "description": ""}]`}},
			want: []string{"has id 99999 in the spec, but the space has no component with that ID", "+ create   Web", "new component",
				`Component "Legacy" is in the space but not in the spec; it is left as it is.`}},
		{name: "a role member only Jira has",
			edit: []string{"  role_members:\n    atlassian-addons-project-access:\n      - user:000000:00000000-0000-0000-0000-000000000002\n",
				"  role_members:\n    atlassian-addons-project-access:\n"},
			want: []string{`Role "atlassian-addons-project-access" has member`, "user:000000:00000000-0000-0000-0000-000000000002 in the space, who is not in the spec"}},
		{name: "a role member the spec adds, without --allow-update",
			edit: []string{"    atlassian-addons-project-access:\n", "    atlassian-addons-project-access:\n      - user:000000:00000000-0000-0000-0000-000000000099\n"},
			want: []string{"✗ error    atlassian-addons-project-access", "which widens access to the",
				"--allow-update=role_members, or add the members by hand"}},
		{name: "a space without a notification scheme, as the spec says",
			section: [3]string{"  notifications:\n", "  issue_security:", "  notifications: null\n"},
			routes:  []jiratest.Route{{Path: "/rest/api/3/project/TS/notificationscheme", Query: url.Values{"expand": {"all"}}, Status: http.StatusNotFound}},
			want:    []string{"✓ exists   Notification scheme  the space has none, as the spec says"}},
		{name: "a spec without notifications for a space that has them",
			section: [3]string{"  notifications:\n", "  issue_security:", "  notifications: null\n"},
			want:    []string{"~ update   Notification scheme  the space stops using", "step 25 removes it"}},
		{name: "an issue layout",
			edit: []string{"\nspace:\n", "\nissue_layouts:\n  - {name: Bug layout}\n\nspace:\n"},
			want: []string{"? manual   Bug layout", "issue layout: set in Jira by hand"}},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			got := tc.run(t)
			for _, w := range tc.want {
				if !strings.Contains(got, w) {
					t.Errorf("output lacks %q:\n%s", w, got)
				}
			}
		})
	}
}

func methodOf(r jiratest.Route) string {
	if r.Method == "" {
		return http.MethodGet
	}
	return r.Method
}
